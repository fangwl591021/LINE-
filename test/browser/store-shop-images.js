// Run in the isolated local store-shop harness; never against production.
async function testStoreShopImages() {
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  const until=async(fn)=>{for(let i=0;i<100;i++){if(fn())return;await new Promise(r=>setTimeout(r,40));}throw Error('Timed out: '+document.body.innerText);};
  document.querySelector('[data-do=manage]').click();
  await until(()=>document.querySelector('[data-form=store]'));
  const form=document.querySelector('[data-form=store]');
  const picker=form.querySelector('input[type=file]');
  const field=picker.closest('.shop-image-field');
  check(form.querySelector('[data-do=upload-image]').textContent==='上傳圖片','missing button');
  check(getComputedStyle(picker).display==='none','native picker not hidden');
  const canvas=document.createElement('canvas');canvas.width=2000;canvas.height=1000;
  const ctx=canvas.getContext('2d');
  ctx.fillStyle='#e7aa31';ctx.fillRect(0,0,2000,1000);ctx.fillStyle='#116e54';ctx.fillRect(0,0,2000,120);ctx.fillRect(0,880,2000,120);
  const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/png'));
  const file=new File([blob],'shop.png',{type:'image/png'});
  const choose=file=>{const transfer=new DataTransfer();if(file)transfer.items.add(file);picker.files=transfer.files;picker.dispatchEvent(new Event('change',{bubbles:true}));};
  let uploads=0,encoded='',release;
  window.fetchAPI=async(action,payload)=>{
    check(action==='uploadImageToR2','wrong action');uploads++;encoded=payload.base64Image;
    return await new Promise(resolve=>{release=()=>resolve({success:true,url:'https://example.test/shop.jpg'});});
  };
  choose(null);check(uploads===0,'cancel uploads');
  choose(new File(['<svg/>'],'bad.svg',{type:'image/svg+xml'}));
  await until(()=>field.querySelector('[role=status]').textContent.includes('未更新'));
  check(uploads===0,'invalid type uploaded');
  choose(new File([new Uint8Array(11*1024*1024)],'large.jpg',{type:'image/jpeg'}));
  await until(()=>field.querySelector('[role=status]').textContent.includes('10MB'));
  choose(new File(['not an image'],'broken.png',{type:'image/png'}));
  await until(()=>field.querySelector('[role=status]').textContent.includes('無法讀取圖片'));
  check(uploads===0,'invalid image content uploaded');
  choose(file);await until(()=>release);
  check(form.querySelector('button').disabled,'save not disabled');
  check(document.querySelector('[data-do=exit]').disabled,'navigation not disabled');
  check(form.elements.name.disabled,'form not locked during upload');
  release();await until(()=>field.querySelector('[role=status]').textContent.includes('圖片已上傳'));
  check(form.elements.image_url.value==='https://example.test/shop.jpg','URL not filled');
  check(form.elements.name.value==='測試店家（不是真實商家）','form lost values');
  const decoded=new Image();decoded.src=encoded;await decoded.decode();
  check(decoded.naturalWidth===1600&&decoded.naturalHeight===800,'image distorted or cropped');
  const old=form.elements.image_url.value;
  window.fetchAPI=async()=>({success:false,error:'測試上傳失敗'});
  choose(file);await until(()=>field.querySelector('[role=status]').textContent.includes('未更新'));
  check(form.elements.image_url.value===old,'failed upload lost original URL');
  check(!form.querySelector('button').disabled,'controls did not recover');
  check(picker.value==='','same file retry blocked');
  const previousVersion=Number(form.dataset.version);
  form.requestSubmit();await until(()=>Number(document.querySelector('[data-form=store]')?.dataset.version)>previousVersion);
  document.querySelector('[data-do=new]').click();
  check(!!document.querySelector('[data-form=product] [data-do=upload-image]'),'product upload missing');
  document.querySelector('[data-do=cancel]').click();
  document.querySelector('[data-do=view]').click();
  await until(()=>document.querySelector('article>img'));
  const image=document.querySelector('article>img');image.src=encoded;await image.decode();
  const rect=image.getBoundingClientRect(),card=image.parentElement.getBoundingClientRect();
  check(Math.abs(rect.width-(card.width-2))<2,'image is not full card width');
  check(Math.abs(rect.width/rect.height-2)<0.02,'display image cropped');
  check(document.documentElement.scrollWidth<=innerWidth,'horizontal overflow');
  return {viewport:innerWidth,uploadAndPreview:true,failedUploadPreservesDraft:true,cancelNoUpload:true,productButton:true,width:rect.width,height:rect.height,encodedSize:encoded.length};
}
