// Run in the isolated local store-shop harness; never against production.
async function testStoreShopImages() {
  if(location.hostname!=='127.0.0.1')throw Error('Isolated loopback fixture only');
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  const until=async(fn)=>{for(let i=0;i<100;i++){if(fn())return;await new Promise(r=>setTimeout(r,40));}throw Error('Timed out: '+document.body.innerText);};
  const saveImage=async form=>{const button=form.querySelector('[data-image-save]');button.scrollIntoView({block:'center'});await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));const r=button.getBoundingClientRect(),hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);check(hit===button||button.contains(hit),'image save button blocked: '+JSON.stringify({hit:hit?.tagName,css:hit?.className,top:r.top,bottom:r.bottom,scroll:scrollY,height:innerHeight}));if(window.clickShopImageSave)await window.clickShopImageSave();else button.click();};
  document.querySelector('[data-do=manage]').click();
  await until(()=>document.querySelector('[data-form=store]'));
  const form=document.querySelector('[data-form=store]');
  const picker=form.querySelector('input[type=file]');
  const field=picker.closest('.shop-image-field');
  const originalImage=form.elements.image_url.value,originalVersion=Number(form.dataset.version);
  check(form.querySelector('[data-do=upload-image]').textContent==='上傳圖片','missing button');
  check(getComputedStyle(picker).display==='none','native picker not hidden');
  const canvas=document.createElement('canvas');canvas.width=2000;canvas.height=1000;
  const ctx=canvas.getContext('2d');
  ctx.fillStyle='#e7aa31';ctx.fillRect(0,0,2000,1000);ctx.fillStyle='#116e54';ctx.fillRect(0,0,2000,120);ctx.fillRect(0,880,2000,120);
  const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/png'));
  const file=new File([blob],'shop.png',{type:'image/png'});
  const choose=file=>{const transfer=new DataTransfer();if(file)transfer.items.add(file);picker.files=transfer.files;picker.dispatchEvent(new Event('change',{bubbles:true}));};
  let uploads=0,encoded='',release;
  window.fetchAPI=async(action,payload)=>{
    check(action==='uploadImageToR2','wrong action');uploads++;encoded=payload.base64Image;
    return await new Promise(resolve=>{release=()=>resolve({success:true,url:'https://example.com/shop.jpg'});});
  };
  choose(null);check(uploads===0,'cancel uploads');
  choose(new File(['<svg/>'],'bad.svg',{type:'image/svg+xml'}));
  await until(()=>field.querySelector('[role=status]').textContent.includes('未更新'));
  check(uploads===0,'invalid type uploaded');
  choose(new File([new Uint8Array(11*1024*1024)],'large.jpg',{type:'image/jpeg'}));
  await until(()=>field.querySelector('[role=status]').textContent.includes('10MB'));
  choose(new File(['not an image'],'broken.png',{type:'image/png'}));
  await until(()=>field.querySelector('[role=status]').textContent.includes('無法讀取圖片'));
  check(uploads===0,'invalid image content uploaded');
  choose(file);await until(()=>release);
  check(form.querySelector('button').disabled,'save not disabled');
  check(document.querySelector('[data-do=exit]').disabled,'navigation not disabled');
  check(form.elements.name.disabled,'form not locked during upload');
  release();await until(()=>field.querySelector('[role=status]').textContent.includes('圖片已上傳'));
  check(form.elements.image_url.value==='https://example.com/shop.jpg','URL not filled');
  check(form.elements.name.value==='測試店家（不是真實商家）','form lost values');
  check(!field.querySelector('[data-image-pending]').hidden,'unsaved image status missing');
  check(field.querySelector('[data-image-save]').textContent==='儲存店面並更新圖片','explicit image save button missing');
  check(field.querySelector('[role=status]').textContent.includes('尚未儲存'),'upload mistaken for saved image');
  await window.captureShopImageStage?.('pending');
  const decoded=new Image();decoded.src=encoded;await decoded.decode();
  check(decoded.naturalWidth===1600&&decoded.naturalHeight===800,'image distorted or cropped');
  const old=form.elements.image_url.value;
  window.fetchAPI=async()=>({success:false,error:'測試上傳失敗'});
  choose(file);await until(()=>field.querySelector('[role=status]').textContent.includes('未更新'));
  check(form.elements.image_url.value===old,'failed upload lost original URL');
  check(!form.querySelector('button').disabled,'controls did not recover');
  check(picker.value==='','same file retry blocked');
  await fetch('/test/image-review?mode=manual');
  await saveImage(form);
  await until(()=>!form.elements.name.disabled&&field.querySelector('[role=status]').textContent.includes('尚未儲存'));
  check(form.elements.image_url.value===old,'AI failure lost uploaded URL');
  check(field.querySelector('.shop-upload-preview img').getAttribute('src')===old,'AI failure lost uploaded preview');
  check(!field.querySelector('[data-image-save]').disabled,'AI failure locked retry');
  await window.captureShopImageStage?.('review-failed');
  const failed=await fetch('/test/image-state').then(r=>r.json());
  check(failed.image_url===originalImage&&failed.version===originalVersion,'AI failure changed saved image');
  const publicAfterFailure=await fetch('/v1/store-shop?shop='+failed.id).then(r=>r.json());
  check(publicAfterFailure.shop.image_url===originalImage,'AI failure published pending image');
  form.elements.description.value+='（合成測試核對後修正介紹）';
  await fetch('/test/image-review?mode=allow');
  await new Promise(resolve=>setTimeout(resolve,3100)); // Preserve the real review cooldown.
  await saveImage(form);
  await until(()=>Number(document.querySelector('[data-form=store]')?.dataset.version)>originalVersion);
  let savedForm=document.querySelector('[data-form=store]');
  check(savedForm.elements.image_url.value===old,'saved management response still has old image');
  check(savedForm.querySelector('[data-image-pending]').hidden,'saved image still marked pending');
  check(savedForm.querySelector('.shop-image-status').textContent.includes('圖片已儲存'),'saved confirmation missing');
  document.querySelector('[data-do=manage]').click();
  await until(()=>document.querySelector('[data-form=store]')?.elements.image_url.value===old);
  savedForm=document.querySelector('[data-form=store]');
  const conflictImage='https://example.com/newer-shop.jpg';
  savedForm.elements.image_url.value=conflictImage;savedForm.elements.image_url.dispatchEvent(new Event('change',{bubbles:true}));
  await fetch('/test/image-version-conflict',{method:'POST'});
  await saveImage(savedForm);
  await until(()=>!savedForm.elements.name.disabled&&savedForm.querySelector('.shop-image-status').textContent.includes('本次儲存未完成'));
  check(savedForm.elements.image_url.value===conflictImage,'version conflict lost pending image');
  check(savedForm.querySelector('.shop-upload-preview img').getAttribute('src')===conflictImage,'manual image URL preview not updated');
  const afterConflict=await fetch('/test/image-state').then(r=>r.json());
  check(afterConflict.image_url===old,'version conflict replaced saved image');
  document.querySelector('[data-do=manage]').click();
  await until(()=>document.querySelector('[data-form=store]')?.elements.image_url.value===old);
  document.querySelector('[data-do=new]').click();
  check(!!document.querySelector('[data-form=product] [data-do=upload-image]'),'product upload missing');
  document.querySelector('[data-do=cancel]').click();
  document.querySelector('[data-do=view]').click();
  await until(()=>document.querySelector('article>img'));
  let image=document.querySelector('article>img');
  check(image.getAttribute('src')===old,'public detail still has old saved image');
  document.querySelector('.shop-bar [data-do=list]').click();
  await until(()=>document.querySelector('.shop-discovery-grid article>img'));
  check(document.querySelector('.shop-discovery-grid article>img').getAttribute('src')===old,'public listing still has old saved image');
  document.querySelector('.shop-discovery-grid [data-do=view]').click();
  await until(()=>document.querySelector('.shop-store-intro>img'));
  image=document.querySelector('.shop-store-intro>img');
  check(image.getAttribute('src')===old,'reopened detail lost saved image');
  image.src=encoded;await image.decode(); // Cropping is checked only after server URL assertions.
  const rect=image.getBoundingClientRect(),card=image.parentElement.getBoundingClientRect();
  check(Math.abs(rect.width-(card.width-2))<2,'image is not full card width');
  check(getComputedStyle(image).objectFit==='cover','store introduction must crop to fill its frame');
  check(Math.abs(rect.height-Math.min(rect.width*9/16,360))<2,'store cover ratio or desktop height cap changed');
  check(document.documentElement.scrollWidth<=innerWidth,'horizontal overflow');
  await window.captureShopImageStage?.('public');
  document.querySelector('.shop-bar [data-do=manage]').click();
  await until(()=>document.querySelector('[data-form=store]'));
  const draftForm=document.querySelector('[data-form=store]'),draftVersion=Number(draftForm.dataset.version);
  draftForm.elements.image_url.value='https://example.com/draft-shop.jpg';draftForm.elements.image_url.dispatchEvent(new Event('change',{bubbles:true}));
  draftForm.elements.status.value='draft';await saveImage(draftForm);
  await until(()=>Number(document.querySelector('[data-form=store]')?.dataset.version)>draftVersion);
  check(document.querySelector('[data-form=store] .shop-image-status').textContent==='圖片已儲存為草稿，尚未公開。','draft photo wrongly announced as public');
  const draftState=await fetch('/test/image-state').then(r=>r.json());
  const hiddenPublic=await fetch('/v1/store-shop?shop='+draftState.id);
  check(hiddenPublic.status===404,'draft photo became public');
  return {viewport:innerWidth,uploadAndPreview:true,explicitImageSave:true,aiFailurePreservesOriginal:true,versionConflictPreservesDraft:true,reopenedManagementImage:true,publicListingImage:true,publicDetailImage:true,draftSavedNotPublished:true,failedUploadPreservesDraft:true,cancelNoUpload:true,productButton:true,width:rect.width,height:rect.height,encodedSize:encoded.length};
}
