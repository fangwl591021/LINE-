const fs = require('fs');
const html = fs.readFileSync('index.html','utf8');
function ok(v,label){if(!v){console.error('FAIL',label);process.exit(1)}console.log('OK',label)}
const start = html.indexOf('id="home-profile-card"');
const end = html.indexOf('id="home-header-site-name"', start);
ok(start >= 0 && end > start, 'shared top banner region found');
const banner = html.slice(start,end);
ok(banner.includes('會員專區'), 'member area remains first banner function');
ok(banner.includes('data-home-top-action="cards"') && banner.includes("window.goPage('card')") && banner.includes('收藏名片'), 'card collection occupies banner slot');
ok(banner.includes('data-home-top-action="customers"') && banner.includes("window.goPage('customers')") && banner.includes('我的客戶'), 'customers occupies banner slot');
ok(banner.includes('data-home-top-action="home"') && banner.includes('返回'), 'home return remains in banner');
ok(!banner.includes('data-home-top-action="points"') && !banner.includes('>購物金</span>'), 'shopping points removed from shared banner');
ok(!banner.includes('data-home-top-action="checkin"') && !banner.includes('簽到贈點'), 'daily checkin removed from shared banner');
ok(!html.includes('aria-label="名片與客戶切換"'), 'lower duplicate card/customer switch nav removed');
const profile = banner.indexOf('會員專區');
const cards = banner.indexOf('收藏名片');
const customers = banner.indexOf('我的客戶');
const home = banner.indexOf('返回');
ok(profile < cards && cards < customers && customers < home, 'banner order is member, cards, customers, home');
console.log('Banner card/customer shortcut contract passed.');
