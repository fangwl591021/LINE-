// Hand-plotted foot positions on the seven 900 x 900 local island illustrations.
// Only paving, stairs and wooden docks are connected. Roofs, pools and the sea
// are not pedestrian shortcuts. Pixel source coordinates make art review clear;
// the exported graph uses normalized coordinates and contains no member data.
const unit = ([x, y]) => [x / 900, y / 900];
const freeze = value => {
  if (value && typeof value === 'object') {
    for (const child of Object.values(value)) freeze(child);
    Object.freeze(value);
  }
  return value;
};
function site({ points, paths, dockIndex, sea, zones = [], corridorWidth = .012 }) {
  const edges = [], added = new Set();
  for (const path of paths) for (let index = 1; index < path.length; index++) {
    const a = path[index - 1], b = path[index], key = [a, b].sort((left, right) => left - right).join(':');
    if (!added.has(key)) { added.add(key); edges.push([a, b]); }
  }
  const normalized = points.map(unit);
  return freeze({ spawn: normalized[0], points: normalized, edges, dockIndex, dock: normalized[dockIndex], sea: unit(sea), corridorWidth, pointRadius: corridorWidth, zones: zones.map(polygon => polygon.map(unit)) });
}

