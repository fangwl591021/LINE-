function normalized(input) {
  return input.normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}

export function matchIndustry(input) {
  const phrase = normalized(input);
  const joined = phrase.replaceAll(' ', '');
  let best = null;
  let specificity = 0;
  for (const industry of industries) {
    for (const term of industry.terms) {
      const cjk = /\p{Script=Han}/u.test(term);
      const matches = cjk ? joined.includes(term) : (' ' + phrase + ' ').includes(' ' + term + ' ');
      const weight = cjk ? term.length * 3 : term.length;
      if (matches && weight > specificity) {
        best = industry;
        specificity = weight;
      }
    }
  }
  return best;
}
