function normalize(value) {
  return value.normalize('NFKC').trim().toLowerCase().replace(/\s+/gu, ' ');
}

const broadLabels = ['顧問','服務業','公司','開店','設計','商業','產業','金融','保險','法律','律師','醫療'];
const profileOption = ({id,label}) => ({id,label});

function matchesTerm(text, rawTerm) {
  const term = normalize(rawTerm);
  if (/[\p{Script=Han}]/u.test(term)) return text.includes(term);
  return (' ' + text.replace(/[^a-z0-9]+/gu, ' ') + ' ').includes(' ' + term + ' ');
}

function findProfiles(text) {
  const exact = profiles.filter(profile => [profile.id,profile.label,...profile.terms].some(term => normalize(term) === text));
  if (exact.length) return exact;
  const candidates = profiles.filter(profile => profile.terms.some(term => matchesTerm(text,term)));
  if (candidates.length !== 1) return candidates;
  // 一種產業以外還有未建模的工作時，請使用者說明要分析哪個項目。
  const pieces = text.split(/(?:[、，,／/&＋+]|兼營|以及|同時經營|與|和)/u).map(part => part.trim()).filter(Boolean);
  if (pieces.some(piece => !candidates[0].terms.some(term => matchesTerm(piece,term)))) return [];
  return candidates;
}

export function analyzeIndustry(input) {
  const text = typeof input === 'string' ? normalize(input) : '';
  const matches = text && text.length <= 60 && !broadLabels.includes(text) ? findProfiles(text) : [];
  if (matches.length !== 1) {
    const question = matches.length > 1
      ? '這個描述包含多種服務。這次想先評估哪一種？'
      : '你主要提供哪一項產品或服務？例如家庭預算規劃、住宅室內設計或民宿住宿。';
    return {status:'clarify', question, options:(matches.length ? matches : profiles).map(profileOption)};
  }
  const profile = matches[0];
  let position = 0;
  const groups = sections.map(({label,criteria:definitions}) => {
    const criteria = definitions.map(([id,name]) => {
      const [score,reason] = profile.ratings[position++];
      if (!Number.isInteger(score) || score < 0 || score > 10 || !reason) throw new TypeError('產業指標資料不完整。');
      return {id,label:name,max:10,score,reason};
    });
    return {label,score:criteria.reduce((sum,item) => sum + item.score,0),max:criteria.length*10,criteria};
  });
  const total = groups.reduce((sum,group) => sum + group.score,0);
  const grade = gradeFor(total);
  const [repeat,partner,first] = profile.offers.map(entry => entry[0]);
  const applications = {
    repurchase:'向已有往來且願意接收消息的客人，介紹「' + repeat + '」的內容、適用時間與預約方式。',
    outflow:profile.out,
    inflow:profile.incoming
  };
  // 一般零售情境示範新客首次消費後獲贈下次使用額度。特殊業務僅在已確認的活動試算折抵。
  const exampleReward = ['dining','retail','beauty','fitness','learning','lodging','travel','local','creative','events','interior'].includes(profile.id) ? 20 : 0;
  const cases = profile.offers.map(([service,originalAmount], index) => {
    const type = ['repurchase','outflow','inflow'][index];
    const discount = profile.infoOnly ? 0 : Math.floor(originalAmount * 0.1);
    return {
      type, service, originalAmount, issued:type === 'inflow' ? exampleReward : 0, discount, actualPayment:originalAmount - discount, illustrative:true,
      benefit:[
        '用「' + repeat + '」觀察既有客戶是否願意再次參與。',
        '讓願意前往的客人認識「' + partner + '」，觀察夥伴承接情形。',
        '以「' + first + '」作為初次接觸，觀察完成預約或參與的人次。'
      ][index]
    };
  });
  const pointsStrategy = profile.infoOnly
    ? '先提供公開資訊。示例贈送及折抵金額均為零，待確認可獨立定價並經審視的非診療活動後再評估。'
    : '先從「' + repeat + '」確認活動範圍與預算。試算假設顧客已有足額購物金，店家允許以原價一成折抵。'
      + (exampleReward ? '首次消費後示範贈 20 元購物金，下次可用。本次實付只扣本次折抵額。' : '活動是否可贈購物金仍需核對，三例的贈額皆為零。');
  return {
    status:'ok', id:profile.id, directoryId:profile.directoryId || profile.id, industry:profile.label, modelVersion:'rules-1.0',
    summary:profile.summary, confidence:'低（僅有產業資料）', assumptions:[profile.assumption,'依臺灣中小業者典型情境估算。尚無個別商家的客群規模、毛利率、回訪率或交易驗證。'],
    groups,total,grade,gradeLabel:grades.find(row => row[1] === grade)[2], applications,pointsStrategy,cases,
    risks:[{risk:profile.risk[0],solution:profile.risk[1]}],
    sales:{
      focus:profile.summary,
      priority:'先與一家夥伴試辦「' + first + '」，記錄曝光、詢問、實際參與及後續回訪。',
      objection:profile.objection,
      invitation:'我們想讓有需要的客人更容易找到彼此。你願意一起試辦「' + first + '」，各自看看有多少客人有興趣嗎？'
    }
  };
}

